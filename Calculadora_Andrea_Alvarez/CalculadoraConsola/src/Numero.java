/**
 * Clase Numero
 * Esta clase representa un número y permite almacenar y recuperar su valor.
 * @version 1.0
 * @author Andrea Álvarez
 * */
public class Numero {
    private float numero;

    public Numero(float numero) {
        this.numero = numero;
    }

    public float getNumero() {
        return numero;
    }

    public void setNumero(float numero) {
        this.numero = numero;
    }


}
